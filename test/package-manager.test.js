const YARN_LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


is-number@^7.0.0:
  version "7.0.0"
  resolved "https://registry.yarnpkg.com/is-number/-/is-number-7.0.0.tgz#7535345b896734d5f80c4d06c50955527a14f12b"
  integrity sha512-41Cifkg6e8TylSpdtTpeLVMqvSBEVzTttHvERD741+pnZ8ANv0004MRL43QKPDlK9cGvNp6NZWZUBlbGXYxxng==
`;

/**
 * @param {Record<string, string>} files
 */
function project(files) {
  let directory = mkdtempSync(join(tmpdir(), "ember-upgrade-"));

  mkdirSync(join(directory, ".git"));

  for (let [file, contents] of Object.entries(files)) {
    mkdirSync(join(directory, file, ".."), { recursive: true });
    writeFileSync(join(directory, file), contents);
  }

  return new Project(directory);
}

test("yarn selectors become pnpm selectors", () => {
  expect(pnpmSelector("**/lodash")).toBe("lodash");
  expect(pnpmSelector("ember-cli-babel/@babel/core")).toBe("ember-cli-babel>@babel/core");
  expect(pnpmSelector("inject-loader/babel-core/json5")).toBe("babel-core>json5");
  expect(pnpmSelector("@ember/test-waiters")).toBe("@ember/test-waiters");
  expect(pnpmSelector("**/@glimmer/**/@glimmer/util")).toBe("@glimmer/util");
});

test("a yarn 1 workspace moves to pnpm, with the same versions", async () => {
  let root = project({
    "package.json": JSON.stringify(
      {
        name: "root",
        private: true,
        workspaces: ["client"],
        resolutions: { "**/is-number": "7.0.0" },
        scripts: { build: "yarn run build:client", "build:client": "yarn --cwd client build" },
      },
      null,
      2,
    ),
    "yarn.lock": YARN_LOCK,
    ".yarnrc": "network-timeout 600000\n",
    ".github/workflows/ci.yml": "steps:\n  - run: yarn install --frozen-lockfile\n",
    "client/package.json": JSON.stringify({
      name: "client",
      dependencies: { "is-number": "^7.0.0" },
    }),
  });
  let app = new Project(join(root.directory, "client"));

  expect(packageManager.detect(app)).toBe(true);

  let todo = await packageManager.run(app);

  expect(packageManager.detect(app)).toBe(false);
  expect(root.has("yarn.lock")).toBe(false);
  expect(root.has(".yarnrc")).toBe(false);
  expect(root.read("pnpm-lock.yaml")).toContain("is-number@7.0.0");
  expect(root.read("pnpm-workspace.yaml")).toBe(
    "packages:\n  - 'client'\n\noverrides:\n  is-number: 7.0.0\n\nstrictDepBuilds: false\nblockExoticSubdeps: false\n",
  );

  let pkg = root.packageJson;

  expect(pkg.packageManager).toMatch(/^pnpm@\d+\./);
  expect(pkg.workspaces).toBeUndefined();
  expect(pkg.resolutions).toBeUndefined();
  expect(pkg.scripts).toEqual({
    build: "pnpm run build:client",
    "build:client": "pnpm --cwd client build",
  });
  expect(todo).toEqual([
    {
      title: "These files still run yarn or npm",
      where: [".github/workflows/ci.yml"],
      action: "Change them to run pnpm.",
    },
  ]);
  expect(readProgress(app).map((entry) => entry.id)).toEqual(["package-manager"]);
}, 120_000);

