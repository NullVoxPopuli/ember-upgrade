test("a yarn 3 app moves to pnpm, with the same versions", async () => {
  let app = project({
    "package.json": JSON.stringify({
      name: "hermes",
      packageManager: "yarn@3.3.0",
      dependencies: { "is-number": "^7.0.0" },
    }),
    "yarn.lock": BERRY_LOCK,
    ".yarnrc.yml": "nodeLinker: node-modules\n",
    ".yarn/releases/yarn-3.3.0.cjs": "",
  });

  expect(packageManager.detect(app)).toBe(true);
  expect(Array.from(hoistedVersions(app, "yarn.lock"))).toEqual([
    ["hermes", "0.0.0-use.local"],
    ["is-number", "7.0.0"],
  ]);

  await packageManager.run(app);

  expect(packageManager.detect(app)).toBe(false);
  expect(app.has("yarn.lock")).toBe(false);
  expect(app.has(".yarnrc.yml")).toBe(false);
  expect(app.has(".yarn")).toBe(false);
  expect(app.read("pnpm-lock.yaml")).toContain("is-number@7.0.0");
  expect(app.packageJson.packageManager).toMatch(/^pnpm@\d+\./);
}, 120_000);

